-- CALORIE COMPASS - SUPABASE / POSTGRESQL SCHEMA

CREATE TABLE IF NOT EXISTS users (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    age SMALLINT NOT NULL CHECK (age BETWEEN 13 AND 100),
    height_cm NUMERIC(5,2) NOT NULL CHECK (height_cm BETWEEN 100 AND 230),
    weight_kg NUMERIC(5,2) NOT NULL CHECK (weight_kg BETWEEN 25 AND 250),
    activity_level VARCHAR(20) NOT NULL
        CHECK (activity_level IN ('sedentary','light','moderate','active')),
    goal VARCHAR(20) NOT NULL
        CHECK (goal IN ('lose','maintain','gain')),
    height_unit VARCHAR(5) NOT NULL DEFAULT 'cm',
    weight_unit VARCHAR(2) NOT NULL DEFAULT 'kg',
    portion_unit VARCHAR(2) NOT NULL DEFAULT 'g',
    email_verified BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS auth_codes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    code_hash VARCHAR(255) NOT NULL,
    purpose VARCHAR(20) NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    used BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_auth_email_purpose
ON auth_codes(email, purpose, used, expires_at);

CREATE TABLE IF NOT EXISTS food_entries (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    food_name VARCHAR(150) NOT NULL,
    meal_type VARCHAR(25) NOT NULL DEFAULT 'Unspecified',
    portion_grams NUMERIC(8,2) NOT NULL,
    calories NUMERIC(10,2) NOT NULL,
    entry_date DATE NOT NULL,
    image_path VARCHAR(255),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_food_user_date
ON food_entries(user_id, entry_date);

CREATE TABLE IF NOT EXISTS activity_entries (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    activity_name VARCHAR(120) NOT NULL,
    duration_minutes INTEGER NOT NULL,
    calories_burned NUMERIC(8,2) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_activity_user
ON activity_entries(user_id);

CREATE TABLE IF NOT EXISTS weight_entries (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    weight_kg NUMERIC(5,2) NOT NULL,
    note VARCHAR(150) DEFAULT '',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_weight_user
ON weight_entries(user_id);

CREATE TABLE IF NOT EXISTS password_reset_sessions (
    session_id CHAR(36) PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    used BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_reset_session_email
ON password_reset_sessions(email);
